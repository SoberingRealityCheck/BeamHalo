"""makes patterns_bh.svh, the beam halo tables for pattern_matcher_bh.sv.

the numbers below are copied by hand from bh_zone_pd and bh_ql in the CMSSW emulator's EMTFModel.cc
(cpp_check/cmssw_src/.../EMTFModel.cc). if that file changes, copy them again.

HACK: the EMTF firmware modules are sized for 3 zones and 7 patterns, and the pipeline latency depends on that. beam halo has 1 and 1.
so the tables are filled out to 3 by 7 with padding, and the matcher forces everything past num_zones_bh and num_patterns_bh
to "no hit". see pattern_matcher_bh.sv.

usage: python3 python/make_patterns_bh.py
"""

NUM_ROWS = 8

OUT = "fpga/beamhalo/beamhalo.srcs/sources_1/new/patterns_bh.svh"
ZONES, PATTERNS = 3, 7        # num_zones_filled and num_patterns_filled in common.svh
PADDING = 55                  # a one column window at the center. never used


def pattern_table(name: str, beam_halo_row_values) -> str:
    """name[zone][pattern][row]. zone 0 pattern 0 is the beam halo pattern. everything else is padding."""
    lines = [f"localparam [31:0] {name}[num_zones_filled][num_patterns_filled][num_hitmap_rows] = '{{"]
    for zone in range(ZONES):
        lines += [f"\t// Zone {zone}", "\t'{"]
        for pattern in range(PATTERNS):
            values = beam_halo_row_values if zone == 0 and pattern == 0 else [PADDING] * NUM_ROWS
            lines.append("\t\t{" + ", ".join(map(str, values)) + "}" + ("," if pattern < PATTERNS - 1 else ""))
        lines.append("\t}" + ("," if zone < ZONES - 1 else ""))
    return "\n".join(lines + ["};"])


def quality_table(name: str, zone0_values) -> str:
    """name[zone][mask]. zone 0 is the beam halo table. the other zones are all 0."""
    lines = [f"localparam [31:0] {name}[num_zones_filled][2 ** num_hitmap_rows] = '{{"]
    for zone in range(ZONES):
        values = zone0_values if zone == 0 else [0] * 2 ** NUM_ROWS
        lines += [f"\t// Zone {zone}", "\t'{"]
        for i in range(0, len(values), 32):
            lines.append("\t\t" + ", ".join(map(str, values[i:i + 32])) + ("," if i + 32 < len(values) else ""))
        lines.append("\t}" + ("," if zone < ZONES - 1 else ""))
    return "\n".join(lines + ["};"])


