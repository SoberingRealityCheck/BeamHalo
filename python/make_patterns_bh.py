# makes patterns_bh.svh: the beam halo pattern tables for pattern_matcher_bh.sv
#
# reads the beam halo pattern (bh_zone_pd) and quality table (bh_ql) straight out of
# Osvaldo's EMTFModel.cc, so the numbers can't get mistyped.
#
# HACK: Patrick's modules are sized for 3 zones x 7 patterns (num_zones, num_patterns
# in common.svh) and the pipeline latency depends on those. beam halo has 1 zone and
# 1 pattern. so we fill the tables out to 3 x 7 with padding and the matcher ignores
# everything past num_zones_bh / num_patterns_bh. see pattern_matcher_bh.sv.
#
# usage: python3 python/make_patterns_bh.py [path/to/EMTFModel.cc]

import sys

from bh_tables import CC, load

OUT = "fpga/beamhalo/beamhalo.srcs/sources_1/new/patterns_bh.svh"
cc_path = sys.argv[1] if len(sys.argv) > 1 else CC

ZONES_FILLED = 3      # num_zones_filled in common.svh
PATTS_FILLED = 7      # num_patterns_filled in common.svh
ROWS = 8              # num_hitmap_rows
PAD = 55              # padding pattern: one column at the center. never used (gated off)

rows, ql = load(cc_path)
start = [r[0] for r in rows]
mid   = [r[1] for r in rows]
stop  = [r[2] for r in rows]

def pattern_table(name, row_values):
    # [zone][patt][row]. zone 0 patt 0 is beam halo. everything else is padding.
    out = [f"localparam [31:0] {name}[num_zones_filled][num_patterns_filled][num_hitmap_rows] = '{{"]
    for z in range(ZONES_FILLED):
        out.append(f"\t// Zone {z}")
        out.append("\t'{")
        for p in range(PATTS_FILLED):
            vals = row_values if (z == 0 and p == 0) else [PAD] * ROWS
            sep = "," if p < PATTS_FILLED - 1 else ""
            out.append("\t\t{" + ", ".join(str(v) for v in vals) + "}" + sep)
        out.append("\t}" + ("," if z < ZONES_FILLED - 1 else ""))
    out.append("};")
    return "\n".join(out)

def activation_table(name, zone0):
    out = [f"localparam [31:0] {name}[num_zones_filled][2 ** num_hitmap_rows] = '{{"]
    for z in range(ZONES_FILLED):
        vals = zone0 if z == 0 else [0] * (2 ** ROWS)
        out.append(f"\t// Zone {z}")
        out.append("\t'{")
        for i in range(0, len(vals), 32):
            chunk = ", ".join(str(v) for v in vals[i:i + 32])
            end = "," if i + 32 < len(vals) else ""
            out.append("\t\t" + chunk + end)
        out.append("\t}" + ("," if z < ZONES_FILLED - 1 else ""))
    out.append("};")
    return "\n".join(out)

svh = f"""// file auto generated by python/make_patterns_bh.py. don't edit by hand.
// source: EMTFModel.cc  bh_zone_pd, bh_ql

// how much of the 3 zone x 7 pattern tables below is real. the rest is padding.
// pattern_matcher_bh.sv forces anything past these to "no activation".
localparam num_zones_bh    = 1;
localparam num_patterns_bh = 1;

// pattern row i covers hitmap columns start..stop around a center of {mid[0]} (same units as his tables).
// centers (not used by the matcher, only by track building): {mid}
{pattern_table("col_start_table_bh", start)}

{pattern_table("col_stop_table_bh", stop)}

// quality of an activation. index = 8 bit mask of which rows the pattern hit (bit i = row i).
{activation_table("pattern_activations_bh", ql)}
"""
open(OUT, "w").write(svh)

# watch it work
print("start per row:", start)
print("stop  per row:", stop)
print("center per row:", mid)
print("quality entries:", len(ql), " nonzero:", sum(1 for q in ql if q), " max:", max(ql))
print("quality when all 8 rows hit (mask 255):", ql[255])
print("wrote", OUT)
